const test = require("node:test");
const assert = require("node:assert/strict");
const { checkGate: strictGate, required } = require("./gate.cjs");
const checkGate = (i, m, r, p = "success", c = "success") =>
  strictGate(i, m, r, p, c);
const inventory = require("../inventory.json");
const meta = { revision: "abc", hashes: { "manifest.json": "123" } };
const receipts = () =>
  required.map((sdk) => ({ sdk, status: "success", ...structuredClone(meta) }));
test("valid ten-SDK matrix passes without Dart or Lua", () =>
  assert.equal(checkGate(inventory, meta, receipts()), true));
for (const status of ["failure", "skipped", "cancelled", undefined]) {
  test(`producer/consumer ${status} fails`, () => {
    // Explicit undefined represents a missing GitHub job result, not the local defaults.
    const bad = status === undefined ? "missing" : status;
    if (status === undefined) {
      assert.throws(() =>
        strictGate(inventory, meta, receipts(), undefined, "success")
      );
      assert.throws(() =>
        strictGate(inventory, meta, receipts(), "success", undefined)
      );
    }
    assert.throws(() => checkGate(inventory, meta, receipts(), bad));
    assert.throws(() => checkGate(inventory, meta, receipts(), "success", bad));
  });
}
for (const sdk of required) {
  test(`missing or broken required ${sdk} fails`, () => {
    assert.throws(() =>
      checkGate(
        inventory,
        meta,
        receipts().filter((r) => r.sdk !== sdk)
      )
    );
    const r = receipts();
    r.find((r) => r.sdk === sdk).status = "failure";
    assert.throws(() => checkGate(inventory, meta, r));
  });
}
test("incompatible generated bytes and stale revision fail", () => {
  const r = receipts();
  r[0].hashes["manifest.json"] = "wrong";
  assert.throws(() => checkGate(inventory, meta, r));
  const s = receipts();
  s[0].revision = "old";
  assert.throws(() => checkGate(inventory, meta, s));
});
test("missing inventory member cannot silently reduce the required gate", () =>
  assert.throws(() => checkGate(inventory.slice(1), meta, receipts())));

test("mutually consistent receipts from another release cannot authorize publishing", () => {
  assert.throws(() => strictGate(inventory, meta, receipts(), "success", "success", "approved-sha"));
  assert.equal(strictGate(inventory, meta, receipts(), "success", "success", "abc"), true);
});
