const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../..");
const source = fs.readFileSync(path.join(root, "contract/compatibility.json"), "utf8").trimEnd();
const output = "// Generated by contract/scripts/generate-swift-compat.cjs. Do not edit.\n"
  + "enum CompatibilityData {\n    static let json = #####\"\"\"\n" + source + "\n\"\"\"#####\n}\n";
const target = path.join(root, "clients/swift/Sources/VexillaClient/CompatibilityData.swift");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output) { throw Error("Swift compatibility data drift"); }
} else { fs.writeFileSync(target, output); }
